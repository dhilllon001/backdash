function secJob(id, title, unit, start, end, opts = {}) {
  const kind = opts.kind || 'gate'
  const photoSet =
    kind === 'fence'
      ? [
          { label: 'Fence line', src: SEC_SHIFT_PH.fence, ago: opts.ago || '3h ago' },
          { label: 'Damage log', src: SEC_SHIFT_PH.fence, ago: '2h ago' },
        ]
      : kind === 'camera'
        ? [
            { label: 'Camera feed', src: SEC_SHIFT_PH.camera, ago: opts.ago || '2h ago' },
            { label: 'NVR status', src: SEC_SHIFT_PH.camera, ago: '1h ago' },
          ]
        : kind === 'visitor'
          ? [
              { label: 'Gate entry', src: SEC_SHIFT_PH.gate, ago: opts.ago || '45m ago' },
              { label: 'Visitor badge', src: SEC_SHIFT_PH.badge, ago: '40m ago' },
              { label: 'ID scan', src: PH.id, ago: '42m ago' },
            ]
          : [
              { label: 'Gate check', src: SEC_SHIFT_PH.gate, ago: opts.ago || '1h ago' },
              { label: 'Badge log', src: SEC_SHIFT_PH.badge, ago: '55m ago' },
            ]
  return {
    id,
    title,
    unit,
    start,
    end,
    actual: opts.actual ?? (end ? '0:20' : '1:05'),
    est: opts.est ?? '0:20',
    checklist: opts.checklist ?? '3/3',
    status: opts.status ?? { tone: 'ok', label: 'Complete' },
    photos: opts.photos ?? photoSet,
  }
}

function secShift({
  id,
  day,
  date,
  yard,
  tz = 'EDT',
  payable,
  barTone,
  hoursLabel,
  inn,
  out = null,
  open = false,
  totalHours,
  productiveHours,
  onJobs,
  jobCount,
  segs,
  jobs,
  exception,
}) {
  const short = String(parseInt(date.slice(-2), 10))
  return {
    id,
    day,
    date,
    short,
    dayOff: false,
    yard,
    tz,
    payable,
    barTone,
    hoursLabel,
    in: inn,
    out,
    open,
    totalHours,
    productiveHours,
    onJobs,
    jobCount: jobCount ?? jobs.length,
    segs,
    jobs,
    ...(exception ? { exception } : {}),
  }
}

