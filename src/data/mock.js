/** Expand a date range into ledger rows (worked days + day offs). */
export function buildShiftLedger(shifts, rangeStart, rangeEnd) {
  const byDate = new Map(shifts.map((s) => [s.date, s]))
  const rows = []
  const start = new Date(`${rangeStart}T12:00:00`)
  const end = new Date(`${rangeEnd}T12:00:00`)
  for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
    const iso = [
      d.getFullYear(),
      String(d.getMonth() + 1).padStart(2, '0'),
      String(d.getDate()).padStart(2, '0'),
    ].join('-')
    const existing = byDate.get(iso)
    if (existing) {
      rows.push(existing)
      continue
    }
    const label = d.toLocaleDateString('en-US', {
      weekday: 'short',
      month: 'short',
      day: 'numeric',
    })
    rows.push({
      id: `off-${iso}`,
      day: label,
      date: iso,
      short: String(d.getDate()),
      dayOff: true,
      yard: '—',
      tz: 'EDT',
      payable: '0:00',
      barTone: 'off',
      hoursLabel: 'Day off',
      in: null,
      out: null,
      totalHours: '0:00',
      productiveHours: '0:00',
      onJobs: '0:00',
      jobCount: 0,
      segs: [],
      jobs: [],
    })
  }
  return rows.reverse()
}
